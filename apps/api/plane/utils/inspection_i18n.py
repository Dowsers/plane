"""Server-side strings for inspection compliance, in the recipient's own
language (ISO/IEC 17020 §4.1/§4.2).

## Why a dict and not Django's gettext

Django's translation machinery expects `.po`/`.mo` catalogues compiled at build
time, and this project ships none - `LocaleMiddleware` is not installed and no
`locale/` directory exists. Introducing that whole apparatus for the ~30 strings
two emails and one PDF need would be a disproportionate change, and it would put
these strings somewhere no reader of the PDF builder would look. So: one table,
keyed by language, with an English fallback.

## Which language

`Profile.language` (default "en"), i.e. the recipient's own setting rather than
the request's. That matters because the two places these strings are used are
asynchronous: a reminder email is composed by a Celery task with no request at
all, and a PDF is rendered for whoever asks, which may be an admin downloading
somebody else's declaration - the DOCUMENT is that signer's, but the labels
around it should read in the language of the person looking at it.

## What is NOT translated, ever

The document body and the questionnaire's question wording. Those are the legal
text the evaluator accepted; an evidentiary record has to reproduce exactly what
was signed, and a translated clause is a different clause. See
`plane.db.models.inspection.DEFAULT_IMPARTIALITY_QUESTIONNAIRE`.
"""

