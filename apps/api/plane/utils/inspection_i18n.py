def normalize_language(language) -> str:
    """Map a `Profile.language` value onto a key of `_STRINGS`.

    Tolerates regional tags (`pt-BR`, `zh-CN`) and casing, falling back to the
    base language and then to English - a profile holding something unexpected
    must never break a reminder email or a PDF download.
    """
    if not language or not isinstance(language, str):
        return FALLBACK_LANGUAGE
    candidate = language.strip()
    if candidate in _STRINGS:
        return candidate
    lowered = candidate.lower().replace("_", "-")
    for key in _STRINGS:
        if key.lower() == lowered:
            return key
    base = lowered.split("-")[0]
    for key in _STRINGS:
        if key.lower().split("-")[0] == base:
            return key
    return FALLBACK_LANGUAGE


def translate(key: str, language=None) -> str:
    """Look `key` up in `language`, falling back to English and then to the key
    itself - a missing string shows as its key rather than crashing a download."""
    resolved = normalize_language(language)
    table = _STRINGS.get(resolved, {})
    if key in table:
        return table[key]
    return _STRINGS[FALLBACK_LANGUAGE].get(key, key)


def supported_languages() -> tuple:
    return tuple(_STRINGS)
